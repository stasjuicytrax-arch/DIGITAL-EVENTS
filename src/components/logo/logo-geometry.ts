/**
 * Векторная геометрия знака DIGITAL EVENTS, восстановленная по old-site/logos/digital-events/*.png.
 * Знак — контур куба в шестиграннике с острой вершиной вверх: внешние грани + внутренние рёбра
 * «из центра вверх» и «из центра к нижней правой вершине». Контур разбит на три детали с зазором:
 *  1 — левая грань + верхняя левая грань + вертикальное ребро (∩);
 *  2 — диагональное ребро + нижняя правая + нижняя левая грани (уголок к нижней правой вершине);
 *  3 — верхняя правая + правая грани.
 * Координаты: центр (0,0), ось Y вверх, R — радиус описанной окружности.
 */
const S3 = Math.sqrt(3)

export type Pt = [number, number]

export function logoPolygons(R = 1, t = 0.21 * R, g = 0.025 * R): Pt[][] {
  const a = (R * S3) / 2 // внешняя апофема
  const ai = a - t // внутренняя апофема
  const Ri = (2 * ai) / S3 // внутренний радиус
  const G = (2 * g) / S3 // вертикальный сдвиг для зазора g у наклонных граней

  const p1: Pt[] = [
    [0, R], // верхняя вершина
    [0, G], // вертикальное ребро заканчивается над диагональным (зазор)
    [-t, t / S3 + G],
    [-t, Ri - t / S3],
    [-ai, Ri / 2],
    [-ai, -ai / S3 + G], // левая грань заканчивается над нижней левой (зазор)
    [-a, (a - 2 * ai) / S3 + G],
    [-a, R / 2],
  ]

  const p2: Pt[] = [
    [-t, t / S3], // начало диагонального ребра под вертикальным
    [a, -R / 2], // верх диагонали приходит в нижнюю правую вершину
    [0, -R],
    [-a, -R / 2],
    [-a, (a - 2 * ai) / S3],
    [0, -Ri],
    [ai - t, -(ai + t) / S3], // нижняя кромка диагонали встречает внутреннюю нижнюю правую грань
    [-t, -t / S3],
  ]

  const p3: Pt[] = [
    [g, R - g / S3], // правее вертикального ребра (зазор)
    [a, R / 2],
    [a, -a / S3 + G], // правая грань заканчивается над диагональю (зазор)
    [ai, -ai / S3 + G],
    [ai, Ri / 2],
    [g, Ri - g / S3],
  ]
  return [p1, p2, p3]
}

/** SVG-path знака (ось Y вниз), круг описан в квадрат size с полями pad */
export function logoSvgPath(size = 100, pad = 0) {
  const R = (size - pad * 2) / 2
  const c = size / 2
  return logoPolygons(R)
    .map((poly) => 'M' + poly.map(([x, y]) => `${(c + x).toFixed(3)} ${(c - y).toFixed(3)}`).join('L') + 'Z')
    .join('')
}
